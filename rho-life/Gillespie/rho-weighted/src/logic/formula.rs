//! The spatial--behavioural logic.
//!
//! Generated, not designed: one structural connective per term former of the
//! signature, one context-labelled modality per rewrite rule together with a
//! choice of redex position, a propositional layer, and two additions (a
//! greatest fixed point and a hidden-name quantifier).
//!
//! [`RhoLogic`] hand-writes the instance for the rho calculus presented in
//! [`crate::syntax`]. That is honest for now — the generated logic is still
//! under development in the feature branch — provided it sits behind the
//! interface the generator will implement, which is DR-W4.

use crate::syntax::{Name, Term};

#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub enum NamePred {
    /// This exact name.
    Exactly(Name),
    /// `n ⊨ @φ` iff `n = @P` with `P ⊨ φ`. Namespace logic: a namespace is
    /// described by a property rather than enumerated. Available only because
    /// names are quoted processes.
    Quote(Box<Formula>),
    Any,
}

/// How a modality quantifies over redex positions. This is what makes the
/// logic *context-labelled* rather than action-labelled: an action-labelled
/// logic sees one label where this one sees as many as there are enabled
/// interactions.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub enum PosQuant {
    Exists,
    Forall,
    /// Pin a position by its channel.
    At(String),
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub enum Cmp {
    Ge,
    Le,
    Eq,
}

pub type FormulaVar = String;

#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub enum Formula {
    Top,
    Bot,
    And(Box<Formula>, Box<Formula>),
    Or(Box<Formula>, Box<Formula>),
    Not(Box<Formula>),

    // ---- structural: one connective per term former ----
    /// Holds of `n!(Q)` with `Q ⊨ φ`.
    Out {
        chan: NamePred,
        body: Box<Formula>,
    },
    /// The analogue on receipts.
    In {
        chan: NamePred,
        body: Box<Formula>,
    },
    /// Separating conjunction: `P ⊨ φ ∣ ψ` iff `P ≡ Q ∣ R` with `Q ⊨ φ`,
    /// `R ⊨ ψ`. Generated by the associative--commutative equational theory of
    /// parallel composition; everything a modal logic cannot say is said here.
    Sep(Box<Formula>, Box<Formula>),
    Zero,
    /// The term is exactly this one, up to structural congruence. Cheap, and
    /// what makes a namespace predicate able to test a name's tag:
    /// `@(Eq(tag) ∣ ⊤)` describes every structured name carrying that tag.
    Eq(Term),
    /// The structural connective generated for the list former: the term is a
    /// list whose element at `index` satisfies `body`. This is what lets a name
    /// predicate *recover the indices* of a structured name, which is the whole
    /// point of namespace logic — in an atomic-name calculus the indices would
    /// have to travel as message payloads and the logic could reach them only
    /// by observing traffic.
    ListAt {
        index: usize,
        body: Box<Formula>,
    },

    /// Sugar for an `n`-fold separating conjunction of `Out(chan)⊤` — how many
    /// messages are pending on a channel. Kept primitive because the nested
    /// form is quadratic to check and this is linear.
    Count {
        chan: NamePred,
        cmp: Cmp,
        n: usize,
    },

    // ---- behavioural: the addition ----
    /// `⟨K_j⟩φ` — a step labelled by the position `j` after which `φ` holds.
    Dia {
        rule: crate::redex::RuleId,
        pos: PosQuant,
        body: Box<Formula>,
    },
    /// `[K_j]φ`.
    Boxm {
        rule: crate::redex::RuleId,
        pos: PosQuant,
        body: Box<Formula>,
    },

    // ---- additions to the template ----
    Nu {
        var: FormulaVar,
        body: Box<Formula>,
    },
    Var(FormulaVar),
}

impl Formula {
    pub fn and(a: Formula, b: Formula) -> Formula {
        Formula::And(Box::new(a), Box::new(b))
    }
    pub fn or(a: Formula, b: Formula) -> Formula {
        Formula::Or(Box::new(a), Box::new(b))
    }
    pub fn not(a: Formula) -> Formula {
        Formula::Not(Box::new(a))
    }
    pub fn sep(a: Formula, b: Formula) -> Formula {
        Formula::Sep(Box::new(a), Box::new(b))
    }
    pub fn out(chan: Name) -> Formula {
        Formula::Out {
            chan: NamePred::Exactly(chan),
            body: Box::new(Formula::Top),
        }
    }
    pub fn inn(chan: Name) -> Formula {
        Formula::In {
            chan: NamePred::Exactly(chan),
            body: Box::new(Formula::Top),
        }
    }
    /// `⟨K⟩φ` with the existential over positions — the common case.
    pub fn dia(body: Formula) -> Formula {
        Formula::Dia {
            rule: crate::redex::COMM,
            pos: PosQuant::Exists,
            body: Box::new(body),
        }
    }
    pub fn boxm(body: Formula) -> Formula {
        Formula::Boxm {
            rule: crate::redex::COMM,
            pos: PosQuant::Forall,
            body: Box::new(body),
        }
    }
    /// A namespace predicate: a communication redex on *any* channel whose
    /// name quotes a process carrying `tag`. One formula for a whole family of
    /// synapses, where a name-keyed presentation would need one key per channel
    /// and would have to be regenerated when the network grew.
    pub fn comm_in_namespace(tag: Term) -> Formula {
        Formula::comm_in_namespace_at(0, Formula::Eq(tag))
    }

    /// The general form: a communication redex on any channel whose name
    /// quotes a list whose `index`th element satisfies `body`. `index = 0`
    /// selects by tag; a later index selects by endpoint, so
    /// "every synapse onto neuron `i`" is one key rather than one per synapse.
    pub fn comm_in_namespace_at(index: usize, body: Formula) -> Formula {
        let np = NamePred::Quote(Box::new(Formula::ListAt {
            index,
            body: Box::new(body),
        }));
        Formula::sep(
            Formula::In {
                chan: np.clone(),
                body: Box::new(Formula::Top),
            },
            Formula::Out {
                chan: np,
                body: Box::new(Formula::Top),
            },
        )
    }

    /// The key shape of the note's §8: a communication redex on a channel.
    pub fn comm_on(chan: Name) -> Formula {
        Formula::sep(Formula::inn(chan.clone()), Formula::out(chan))
    }

    /// Structural depth (note, Definition 4). Modal formers do not contribute
    /// to structural depth; they are counted separately by [`Formula::modal_depth`].
    pub fn depth(&self) -> usize {
        match self {
            Formula::Top | Formula::Bot | Formula::Zero | Formula::Var(_) => 0,
            Formula::Eq(_) => 0,
            Formula::ListAt { body, .. } => 1 + body.depth(),
            Formula::Count { .. } => 1,
            Formula::Not(a) | Formula::Nu { body: a, .. } => a.depth(),
            Formula::And(a, b) | Formula::Or(a, b) => a.depth().max(b.depth()),
            Formula::Sep(a, b) => a.depth().max(b.depth()),
            Formula::Out { chan, body } | Formula::In { chan, body } => {
                1 + body.depth().max(name_depth(chan))
            }
            Formula::Dia { body, .. } | Formula::Boxm { body, .. } => body.depth(),
        }
    }

    /// Nesting of behavioural modalities. This is the quantity that costs
    /// exponentially, since each level enumerates all successors.
    pub fn modal_depth(&self) -> usize {
        match self {
            Formula::Top | Formula::Bot | Formula::Zero | Formula::Var(_) => 0,
            Formula::Eq(_) => 0,
            Formula::ListAt { body, .. } => body.modal_depth(),
            Formula::Count { .. } => 0,
            Formula::Not(a) | Formula::Nu { body: a, .. } => a.modal_depth(),
            Formula::And(a, b) | Formula::Or(a, b) | Formula::Sep(a, b) => {
                a.modal_depth().max(b.modal_depth())
            }
            Formula::Out { chan, body } | Formula::In { chan, body } => {
                body.modal_depth().max(name_modal_depth(chan))
            }
            Formula::Dia { body, .. } | Formula::Boxm { body, .. } => 1 + body.modal_depth(),
        }
    }

    pub fn has_fixpoint(&self) -> bool {
        match self {
            Formula::Nu { .. } => true,
            Formula::Top | Formula::Bot | Formula::Zero | Formula::Var(_) => false,
            Formula::Eq(_) => false,
            Formula::ListAt { body, .. } => body.has_fixpoint(),
            Formula::Count { .. } => false,
            Formula::Not(a) => a.has_fixpoint(),
            Formula::And(a, b) | Formula::Or(a, b) | Formula::Sep(a, b) => {
                a.has_fixpoint() || b.has_fixpoint()
            }
            Formula::Out { chan, body } | Formula::In { chan, body } => {
                body.has_fixpoint() || name_has_fixpoint(chan)
            }
            Formula::Dia { body, .. } | Formula::Boxm { body, .. } => body.has_fixpoint(),
        }
    }

    /// Whether a fixed-point variable occurs only positively, which
    /// Knaster--Tarski requires.
    pub fn positive_in(&self, var: &str, polarity: bool) -> bool {
        match self {
            Formula::Var(v) if v == var => polarity,
            Formula::Top | Formula::Bot | Formula::Zero | Formula::Var(_) => true,
            Formula::Eq(_) => true,
            Formula::ListAt { body, .. } => body.positive_in(var, polarity),
            Formula::Count { .. } => true,
            Formula::Not(a) => a.positive_in(var, !polarity),
            Formula::And(a, b) | Formula::Or(a, b) | Formula::Sep(a, b) => {
                a.positive_in(var, polarity) && b.positive_in(var, polarity)
            }
            Formula::Out { body, .. } | Formula::In { body, .. } => body.positive_in(var, polarity),
            Formula::Dia { body, .. } | Formula::Boxm { body, .. } => {
                body.positive_in(var, polarity)
            }
            Formula::Nu { body, var: v } => {
                if v == var {
                    true
                } else {
                    body.positive_in(var, polarity)
                }
            }
        }
    }

    pub fn render(&self) -> String {
        match self {
            Formula::Top => "T".into(),
            Formula::Bot => "F".into(),
            Formula::Zero => "0".into(),
            Formula::Eq(t) => format!("={}", t.render()),
            Formula::ListAt { index, body } => format!("[{}]{}", index, body.render()),
            Formula::Var(v) => v.clone(),
            Formula::And(a, b) => format!("({} & {})", a.render(), b.render()),
            Formula::Or(a, b) => format!("({} | {})", a.render(), b.render()),
            Formula::Not(a) => format!("~{}", a.render()),
            Formula::Sep(a, b) => format!("({} ∣ {})", a.render(), b.render()),
            Formula::Out { chan, body } => format!("out({}){}", render_np(chan), body.render()),
            Formula::In { chan, body } => format!("in({}){}", render_np(chan), body.render()),
            Formula::Count { chan, cmp, n } => format!(
                "#{}{}{}",
                render_np(chan),
                match cmp {
                    Cmp::Ge => ">=",
                    Cmp::Le => "<=",
                    Cmp::Eq => "==",
                },
                n
            ),
            Formula::Dia { pos, body, .. } => format!("<K{}>{}", render_pos(pos), body.render()),
            Formula::Boxm { pos, body, .. } => format!("[K{}]{}", render_pos(pos), body.render()),
            Formula::Nu { var, body } => format!("nu {}.{}", var, body.render()),
        }
    }
}

fn render_np(n: &NamePred) -> String {
    match n {
        NamePred::Exactly(nm) => nm.key(),
        NamePred::Quote(f) => format!("@{}", f.render()),
        NamePred::Any => "_".into(),
    }
}

fn render_pos(p: &PosQuant) -> String {
    match p {
        PosQuant::Exists => "".into(),
        PosQuant::Forall => "".into(),
        PosQuant::At(c) => format!("@{c}"),
    }
}

fn name_depth(n: &NamePred) -> usize {
    match n {
        NamePred::Quote(f) => f.depth(),
        _ => 0,
    }
}
fn name_modal_depth(n: &NamePred) -> usize {
    match n {
        NamePred::Quote(f) => f.modal_depth(),
        _ => 0,
    }
}
fn name_has_fixpoint(n: &NamePred) -> bool {
    match n {
        NamePred::Quote(f) => f.has_fixpoint(),
        _ => false,
    }
}

