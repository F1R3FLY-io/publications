/// The note's methodological commitment made into a type: the *ideal* logic
/// defines, restricted *fragments* decide. A logic whose model checking
/// terminates is necessarily not adequate for the whole of a Turing-complete
/// host, so the restriction is not a compromise but the price of executability.
#[derive(Clone, Copy, Debug)]
pub struct Budget {
    pub modal_depth: u8,
    pub inference_tokens: u64,
    pub states: u32,
}

impl Default for Budget {
    fn default() -> Self {
        Budget {
            modal_depth: 3,
            inference_tokens: 1_000_000,
            states: 100_000,
        }
    }
}

impl Budget {
    pub fn spend(&mut self, n: u64) -> Result<(), CheckError> {
        if self.inference_tokens < n {
            self.inference_tokens = 0;
            return Err(CheckError::BudgetExhausted);
        }
        self.inference_tokens -= n;
        Ok(())
    }
}

#[derive(Clone, PartialEq, Eq, Debug)]
pub enum CheckError {
    BudgetExhausted,
    StateSpaceExceeded,
    UnboundVariable(String),
}

/// Why a formula was refused as a key. Diagnostics name the offending
/// subformula: a modeller who writes an unbounded key should get a message, not
/// a hung simulation.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum WhyNot {
    TooDeep { got: usize, budget: u8, at: String },
    UnboundedFixpoint { at: String },
    NegativeFixpointVariable { var: String, at: String },
}

impl std::fmt::Display for WhyNot {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            WhyNot::TooDeep { got, budget, at } => write!(
                f,
                "modal depth {got} exceeds budget {budget}, in subformula `{at}`"
            ),
            WhyNot::UnboundedFixpoint { at } => write!(
                f,
                "greatest fixed point requires a known-finite reachable set, in `{at}`"
            ),
            WhyNot::NegativeFixpointVariable { var, at } => write!(
                f,
                "fixed-point variable `{var}` occurs negatively, in `{at}`"
            ),
        }
    }
}

/// A formula admitted to a checkable fragment. Key sets are `Checkable`;
/// post-hoc properties need not be.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct Checkable(Formula);

impl Checkable {
    pub fn try_new(f: Formula, b: &Budget, finite_state_space: bool) -> Result<Checkable, WhyNot> {
        let md = f.modal_depth();
        if md > b.modal_depth as usize {
            return Err(WhyNot::TooDeep {
                got: md,
                budget: b.modal_depth,
                at: f.render(),
            });
        }
        if f.has_fixpoint() && !finite_state_space {
            return Err(WhyNot::UnboundedFixpoint { at: f.render() });
        }
        if let Some(bad) = negative_fixpoint_var(&f) {
            return Err(WhyNot::NegativeFixpointVariable {
                var: bad,
                at: f.render(),
            });
        }
        Ok(Checkable(f))
    }

    /// Escape hatch for keys whose checkability is guaranteed by construction
    /// (depth-2 channel predicates, for instance).
    pub fn trusted(f: Formula) -> Checkable {
        Checkable(f)
    }

    pub fn formula(&self) -> &Formula {
        &self.0
    }

    pub fn render(&self) -> String {
        self.0.render()
    }
}

fn negative_fixpoint_var(f: &Formula) -> Option<String> {
    match f {
        Formula::Nu { var, body } => {
            if !body.positive_in(var, true) {
                Some(var.clone())
            } else {
                negative_fixpoint_var(body)
            }
        }
        Formula::Not(a) => negative_fixpoint_var(a),
        Formula::And(a, b) | Formula::Or(a, b) | Formula::Sep(a, b) => {
            negative_fixpoint_var(a).or_else(|| negative_fixpoint_var(b))
        }
        Formula::Out { body, .. }
        | Formula::In { body, .. }
        | Formula::Dia { body, .. }
        | Formula::Boxm { body, .. } => negative_fixpoint_var(body),
        _ => None,
    }
}

/// Convenience: `⊨` on the term level, exposed for tests.
pub fn term_is_zero(t: &Term) -> bool {
    matches!(t.canonical(), Term::Zero)
}
